// Real mouse interaction test: orbit, zoom, select by click, gizmo drag, undo, film export.
import {createRequire} from 'node:module';
const require = createRequire('/Users/jurek/openclaw/node_modules/');
const {chromium} = require('playwright-core');
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 }, acceptDownloads: true, locale: 'pl-PL' });
const page = await ctx.newPage();
const logs = [];
page.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') logs.push(`[${m.type()}] ${m.text()}`); });
page.on('pageerror', e => logs.push(`[pageerror] ${e.message}`));
await page.goto('http://127.0.0.1:8979/?scene=checker', { waitUntil: 'load' });
await page.waitForFunction(() => window.HOODOO && document.body.classList.contains('ready'), null, { timeout: 120000 });
const st = () => page.evaluate(() => ({ cam: HOODOO.scene.camera.pos.map(v => +v.toFixed(2)), yaw: +HOODOO.scene.camera.yaw.toFixed(1), sel: HOODOO.selected?.name || null, pos: HOODOO.selected?.pos.map(v => +v.toFixed(2)) }));
const out = {};
out.start = await st();
await page.mouse.move(640, 300); await page.mouse.down(); await page.mouse.move(700, 290, { steps: 8 }); await page.mouse.up();
out.orbit = await st();
await page.mouse.move(640, 420); await page.mouse.wheel(0, -120); await page.waitForTimeout(300);
out.zoom = await st();
const sp = await page.evaluate(() => { const o = HOODOO.scene.objects.find(x => x.type === 'sphere' && x.mat.preset === 'chrome'); const p = HOODOO.project(o.pos); return p; });
await page.mouse.click(sp[0], sp[1]); await page.waitForTimeout(200);
out.click = await st();
const g = await page.evaluate(() => { const o = HOODOO.selected; const f = HOODOO.gizmoFrame(o); const e = HOODOO.project([o.pos[0] + f.size * 0.8, o.pos[1], o.pos[2]]); return e; });
await page.mouse.move(g[0], g[1]); await page.mouse.down(); await page.mouse.move(g[0] + 80, g[1], { steps: 6 }); await page.mouse.up();
out.gizmo = await st();
await page.keyboard.press('Meta+z'); await page.waitForTimeout(200);
out.undo = await st();
out.ui = await page.evaluate(() => ({ hint: document.getElementById('hint').textContent, render: document.querySelector('.render-btn').textContent }));
await page.evaluate(() => { const c = HOODOO.scene.anim.tracks; HOODOO.setTime(0); import('/src/anim/anim.js').then(m => { m.keyCamera(HOODOO.scene, 0); HOODOO.scene.camera.pos[0] += 10; m.keyCamera(HOODOO.scene, 1); HOODOO.scene.anim.duration = 1; HOODOO.emit('anim'); }); });
await page.waitForTimeout(300);
const dl = page.waitForEvent('download', { timeout: 120000 }).catch(() => null);
await page.click('#timeline .btn'); await page.waitForTimeout(300);
await page.evaluate(() => { const s = [...document.querySelectorAll('.pop select')]; s[0].value = '1280x720'; s[0].dispatchEvent(new Event('change')); s[1].value = '24'; s[1].dispatchEvent(new Event('change')); s[2].value = 'draft'; s[2].dispatchEvent(new Event('change')); });
const t0 = Date.now();
await page.click('.pop .btn.accent');
const d = await dl;
if (d) { const p = '/tmp/hoodoo-film.mp4'; await d.saveAs(p); out.film = { file: d.suggestedFilename(), ms: Date.now() - t0 }; } else out.film = 'no download';
await page.screenshot({ path: '/tmp/hoodoo-int.png' });
console.log(JSON.stringify(out, null, 1));
console.log(logs.slice(-15).join('\n'));
await browser.close();
